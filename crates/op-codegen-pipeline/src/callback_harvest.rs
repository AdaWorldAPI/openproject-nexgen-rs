pub fn filter_matches(d: &Filter, f: &FiredFilter) -> bool {
    match (d, f) {
        (Filter::Method(a), FiredFilter::Method(b)) => a == b,
        (
            Filter::Validator { kind: k1, attr: a1 },
            FiredFilter::Validator { kind: k2, attr: a2 },
        ) => k1 == k2 && a1 == a2,
        (Filter::ValidatesWith(a), FiredFilter::ValidatesWith(b)) => {
            let a = a.trim_start_matches("::");
            b == a || b.ends_with(&format!("::{a}"))
        }
        _ => false,
    }
}

pub fn declared_matches(d: &Declared, f: &Fired) -> bool {
    d.chain == f.chain && d.kind == f.kind && filter_matches(&d.filter, &f.filter)
}

/// The negative control: every declared filter spelled backwards.
pub fn reversed(d: &Declared) -> Declared {
    let rev = |s: &str| s.chars().rev().collect::<String>();
    let mut out = d.clone();
    out.filter = match &d.filter {
        Filter::Method(n) => Filter::Method(rev(n)),
        Filter::Validator { kind, attr } => Filter::Validator {
            kind: rev(kind),
            attr: rev(attr),
        },
        Filter::ValidatesWith(n) => Filter::ValidatesWith(rev(n)),
        Filter::Block => Filter::Block,
    };
    out
}

pub struct ModelCtx {
    /// Declared in source, ancestors in the walk's visit order.
    pub declared: Vec<Declared>,
    /// Generated by ActiveRecord from the association declarations.
    pub generated: Vec<Declared>,
    /// Rules `rails_generated` could not decide for this model.
    pub undecided: Vec<UndecidedRow>,
    /// Associations declared with `has_and_belongs_to_many`.
    pub habtm: BTreeSet<String>,
    /// Source plus generated callbacks in Rails registration order.
    pub effective: Vec<Declared>,
    pub assocs: BTreeSet<String>,
    pub ancestor_files: BTreeSet<String>,
    pub has_file: bool,
    /// Every module (concern or patch) in the model's chain and how much of
    /// its include-time bodies ruff read. Class bodies are not listed:
    /// `ClassOre::unharvested` is empty for a class by construction.
    pub modules: Vec<ModuleRead>,
    /// Names of modules whose include-time bodies leave a statement that may
    /// hide a registration and that [`makes_order_unknown`]: a dynamic `send`,
    /// an unread block body, or a conditional whose branches ruff did not read
    /// in full. A callback registered in one of them has no definite position
    /// in the chain. A conditional with `Unharvested::hidden_complete` does not
    /// count: its `hidden` list is exhaustive and goes to `order_hidden`.
    pub order_unknown_scopes: BTreeSet<String>,
    /// What the skipped branches of the hiding conditionals could register, as
    /// far as ruff names it: a conditional whose branches hold only
    /// associations, callbacks and validations ruff can read
    /// (`Unharvested::hidden`), derived like any declaration (its generated
    /// callbacks included). Such a branch can change the order of the compared
    /// entries by registering, or re-registering (ActiveSupport moves a
    /// re-registered callback to the end of its chain,
    /// activesupport-8.1.4.1/lib/active_support/callbacks.rb:645-663), a
    /// callback the recording shows; a group in a scope that is not in
    /// `order_unknown_scopes` and none of whose entries one of these names
    /// stays definite. For a conditional with `hidden_complete` the list is
    /// all its branches could register; for an incomplete one it is a lower
    /// bound (that scope is in `order_unknown_scopes`). Either way it only ever
    /// demotes groups. The origin of each is its scope.
    pub order_hidden: Vec<Declared>,
}

/// Whether a skipped branch of `ctx` could register the fired callback `f`
/// (see [`ModelCtx::order_hidden`]).
pub fn hidden_could_register(ctx: &ModelCtx, f: &Fired) -> bool {
    ctx.order_hidden.iter().any(|d| declared_matches(d, f))
}

/// The callbacks a hiding statement could register, or `None` when it cannot
/// be named: it is not a conditional, it holds a declaration whose callbacks
/// are not derivable here (an `include`, a macro), or a generated rule for it
/// is undecided.
pub fn hidden_registrations(
    u: &ruff_ruby_spo::events::Unharvested,
    scope: &str,
    host: &str,
) -> Option<Vec<Declared>> {
    if u.reason != UnharvestedReason::ControlFlow {
        return None;
    }
    if u.hidden.is_empty() {
        // Nothing the branches could register: that is a fact only when ruff
        // read every branch statement (`hidden_complete`); otherwise there is
        // nothing to name.
        return u.hidden_complete().then(Vec::new);
    }
    let nameable = u.hidden.iter().all(|e| {
        matches!(
            e.decl,
            Declaration::Association(_) | Declaration::Callback(_) | Declaration::Validation(_)
        )
    });
    if !nameable {
        return None;
    }
    let g = generated_from(Some(host), scope, &u.hidden);
    if !g.undecided.is_empty() {
        return None;
    }
    let mut out = declared_of(scope, &u.hidden);
    out.extend(g.callbacks.into_iter().map(|(_, d)| d));
    Some(out)
}

/// How much of one module's include-time bodies was read.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Completeness {
    /// Declarations came out and nothing is listed unharvested.
    Full,
    /// Declarations came out and statements are listed unharvested.
    Partial,
    /// No declaration came out and statements are listed unharvested.
    Unread,
    /// No include-time body produced a declaration or an unread statement
    /// (the module has none, or it is empty): nothing to read.
    NoIncludeTimeBody,
}

impl Completeness {
    pub fn all() -> &'static [Completeness] {
        &[
            Completeness::Full,
            Completeness::Partial,
            Completeness::Unread,
            Completeness::NoIncludeTimeBody,
        ]
    }
}

#[derive(Debug, Clone)]
pub struct ModuleRead {
    pub name: String,
    pub file: String,
    /// Declarations from `included do` / `def self.included` bodies.
    pub included_decls: usize,
    /// Unharvested statements per `UnharvestedReason::as_str`.
    pub unharvested: BTreeMap<String, usize>,
    pub completeness: Completeness,
    /// Whether the intake applied it as an engine patch (else a concern).
    pub is_patch: bool,
}

pub fn classify(f: &Fired, ctx: &ModelCtx, ev: &Evidence) -> (Slag, String) {
    if !ctx.has_file {
        return (
            Slag::ModelWithoutClassFile,
            "no class file in the walked roots".into(),
        );
    }
    let model = f.model.as_str();
    match &f.filter {
        FiredFilter::Method(name) => {
            let assoc = name
                .strip_prefix("autosave_associated_records_for_")
                .or_else(|| name.strip_prefix("validate_associated_records_for_"));
            if let Some(x) = assoc {
                if ctx.assocs.contains(x) {
                    if let Some(u) = ctx.undecided.iter().find(|u| u.association == x) {
                        return (
                            Slag::GeneratedUndecided,
                            format!("association :{x}: {} ({})", u.reason, u.rule),
                        );
                    }
                    return (
                        Slag::AssociationAutosave,
                        format!("association :{x} declared"),
                    );
                }
                // The middle has_many of a habtm is named
                // `[<class>.downcase.pluralize, <assoc>].sort.join("_")`
                // (builder/has_and_belongs_to_many.rb:228-230). This guess only
                // picks the slag reason; it never produces a match.
                let plural = format!("{}s", model.to_lowercase());
                if let Some(h) = ctx.habtm.iter().find(|h| {
                    let mut pair = [plural.as_str(), h.as_str()];
                    pair.sort_unstable();
                    pair.join("_") == x
                }) {
                    return (
                        Slag::GeneratedUndecided,
                        format!("middle has_many of habtm :{h} (name needs the inflector)"),
                    );
                }
                if let Some(f) = ev
                    .assocs
                    .get(x)
                    .and_then(|fs| fs.iter().find(|f| ctx.ancestor_files.contains(*f)))
                {
                    return (
                        Slag::ChainFileNotHarvested,
                        format!("association :{x} is spelled in {f}, a harvested file; no declaration came out"),
                    );
                }
                let files = ev.relevant(ev.assocs.get(x), model, ctx);
                // A plugin or engine file is the more specific explanation; a
                // lone file in the walked roots that merely names the model is
                // not evidence of an association on it.
                let best = files.iter().max_by_key(|p| bucket(p));
                return match best.map(|p| (p, bucket(p))) {
                    Some((p, Bucket::Plugin)) => (
                        Slag::AssociationFromPlugin,
                        format!("association :{x} declared in {p}"),
                    ),
                    Some((p, Bucket::Module)) => (
                        Slag::AssociationFromModule,
                        format!("association :{x} declared in {p}"),
                    ),
                    _ => (
                        Slag::AssociationNotInCheckout,
                        format!("no declaration of :{x} that concerns {model}"),
                    ),
                };
            }
            let files = ev.relevant(ev.defs.get(name), model, ctx);
            match files.iter().map(|p| bucket(p)).max() {
                None => (
                    Slag::FromGem,
                    "no `def` in the checkout that concerns the model".into(),
                ),
                Some(b) => {
                    let slag = match b {
                        Bucket::Walked => Slag::DefinedInWalkedRootsNotDeclared,
                        Bucket::Module => Slag::DefinedInModule,
                        Bucket::Plugin => Slag::DefinedInPlugin,
                    };
                    (slag, format!("def in {}", files[0]))
                }
            }
        }
        FiredFilter::Validator { kind, attr } => {
            if kind == "presence" {
                if let Some(u) = ctx.undecided.iter().find(|u| &u.association == attr) {
                    return (
                        Slag::GeneratedUndecided,
                        format!("association :{attr}: {} ({})", u.reason, u.rule),
                    );
                }
            }
            if let Some(f) = ev
                .validates
                .get(attr)
                .and_then(|fs| fs.iter().find(|f| ctx.ancestor_files.contains(*f)))
            {
                return (
                    Slag::ChainFileNotHarvested,
                    format!("validation of :{attr} is spelled in {f}, a harvested file; no declaration came out"),
                );
            }
            let files = ev.relevant(ev.validates.get(attr), model, ctx);
            match files.iter().find(|p| bucket(p) == Bucket::Module) {
                Some(p) => (
                    Slag::ValidatorFromModule,
                    format!("validation of :{attr} in {p}"),
                ),
                None => (
                    Slag::ValidatorFromFramework,
                    format!("no module line validating :{attr} for {model}"),
                ),
            }
        }
        FiredFilter::ValidatesWith(c) => {
            (Slag::ValidatesWithUndeclared, format!("validates_with {c}"))
        }
    }
}

/// `if:` / `unless:` on the declaration, or inside the option hash of the
/// validator kind it declares (`validates :a, presence: { if: -> { ... } }`).
pub fn has_condition(d: &Declared) -> bool {
    let cond = |v: &str| v.contains(":if") || v.contains(":unless");
    d.options.iter().any(|(k, v)| {
        k == "if"
            || k == "unless"
            || matches!(&d.filter, Filter::Validator { kind, .. } if kind == k && cond(v))
    })
}

/// The chains a model's recorded entries show ran: the chains of its fired
/// entries, plus `validate` when both `validation` and `save` fired. A `save`
/// that ran its callbacks passed `perform_validations`
/// (activerecord-8.1.4.1/lib/active_record/validations.rb:47-48, :90-92), and
/// a `before_validation` that fired means it was not `validate: false`, so
/// `valid?` ran `run_validations!`, whose `validation` callbacks wrap the
/// `validate` chain (activemodel-8.1.4.1/lib/active_model/validations/callbacks.rb:124-126,
/// `_run_validation_callbacks { super }`; validations.rb:463-466,
/// `_run_validate_callbacks`). A `validate` chain whose only callbacks were
/// conditions that held false records nothing, though it ran.
pub fn exercised_chains(fired: &BTreeSet<String>) -> BTreeSet<String> {
    let mut out = fired.clone();
    if fired.contains("validation") && fired.contains("save") {
        out.insert("validate".to_string());
    }
    out
}

pub fn silent_reason(d: &Declared, fired_chains: &BTreeSet<String>) -> Silent {
    if d.filter == Filter::Block {
        return Silent::BlockOrLambdaFilter;
    }
    if !fired_chains.contains(&d.chain) {
        return Silent::ChainNotExercised;
    }
    let on = d
        .options
        .iter()
        .find(|(k, _)| k == "on")
        .map(|(_, v)| v.clone())
        .or_else(|| d.implied_on.map(|s| format!(":{s}")));
    if let Some(on) = &on {
        if !on.contains("create") {
            return Silent::OnOptionNotExercised;
        }
    }
    if on.is_some() || has_condition(d) {
        return Silent::ConditionalOptionNotEvaluated;
    }
    Silent::Unexplained
}

pub fn harvest_for(src: &Path, cfg: &IntakeCfg) -> Harvest {
    let roots = cfg
        .roots
        .list
        .iter()
        .flat_map(|pat| expand_dirs(src, pat))
        .collect();
    let mut h = Harvest::new(src, roots);
    h.indexed_dirs = cfg
        .roots
        .indexed
        .iter()
        .flat_map(|pat| expand_dirs(src, pat))
        .collect();
    h.macros = cfg.macros.rules.clone();
    h.macro_defines = cfg.macros.defines.clone();
    h.inflections = cfg
        .roots
        .inflections
        .iter()
        .map(|i| (underscore(&i.constant), i.file.clone()))
        .collect();
    h
}

pub fn contexts(
    h: &mut Harvest,
    models: &BTreeSet<String>,
    patches: &PatchIntake,
) -> (BTreeMap<String, ModelCtx>, Vec<(String, String)>) {
    h.unresolved.clear();
    let mut out = BTreeMap::new();
    // The class-level macros each model's chain calls, for classes a macro
    // defines (`macros.defines`).
    let mut called: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for m in models {
        let mut ancestors = h.linearize_in(m, m);
        let has_file = !ancestors.is_empty();
        let mut seen: BTreeSet<String> = ancestors.iter().map(|a| a.name.clone()).collect();
        for p in patches.for_model(m).filter(|p| p.how == How::Include) {
            for a in h.linearize_in(&p.patch_name, m) {
                if seen.insert(a.name.clone()) {
                    ancestors.push(a);
                }
            }
        }
        let patch_names: BTreeSet<&str> = patches
            .for_model(m)
            .filter(|p| p.how == How::Include)
            .map(|p| p.patch_name.as_str())
            .collect();
        called.insert(
            m.clone(),
            ancestors
                .iter()
                .flat_map(|a| a.ore.declarations.iter())
                .filter_map(|e| macro_dsl_of(&e.decl))
                .collect(),
        );
        let effective = h.effective(m, patches);
        out.insert(
            m.clone(),
            build_ctx(&ancestors, has_file, &patch_names, effective),
        );
    }
    // A class no file defines may be defined by a macro another model calls
    // (closure_tree's `<Model>Hierarchy`): build its context from the macro's
    // body and its superclass chain.
    for m in models {
        if out[m].has_file || !h.macros_enabled {
            continue;
        }
        let defines = h.macro_defines.clone();
        for def in &defines {
            let Some(host) = models.iter().find(|host| {
                out[*host].has_file
                    && called[*host].contains(&def.by)
                    && fill(&def.class, &[("host", host.as_str())]) == *m
            }) else {
                continue;
            };
            let Some(run) = h.defined_class_run(def) else {
                continue;
            };
            let mut ancestors = h.linearize_in(&def.superclass, m);
            let effective = h.effective_defined(m, &def.superclass, &run);
            ancestors.push(Ancestor {
                name: run.owner,
                file: run.file,
                ore: run.ore,
                host: m.clone(),
            });
            h.macro_log.push(format!(
                "{m}: defined by `{}` called in {host}; superclass {}",
                def.by, def.superclass
            ));
            out.insert(
                m.clone(),
                build_ctx(&ancestors, true, &BTreeSet::new(), effective),
            );
            break;
        }
    }
    (out, h.unresolved.clone())
}

/// The class-body call a declaration is, as a macro name (`acts_as_list`,
/// `has_closure_tree`, a bare `DslCall`), or `None` for any other declaration.
pub fn macro_dsl_of(decl: &Declaration) -> Option<String> {
    match decl {
        Declaration::ActsAs(a) => Some(format!("acts_as_{}", a.variant)),
        Declaration::GemDsl(g) => Some(underscore(&format!("{:?}", g.gem))),
        Declaration::DslCall(c) => Some(c.name.clone()),
        _ => None,
    }
}

/// One model's context from its ancestors in visit order and its effective
/// callback order.
fn build_ctx(
    ancestors: &[Ancestor],
    has_file: bool,
    patch_names: &BTreeSet<&str>,
    effective: Vec<Declared>,
) -> ModelCtx {
    let mut declared = Vec::new();
    let mut generated = Vec::new();
    let mut undecided = Vec::new();
    let mut habtm = BTreeSet::new();
    for a in ancestors {
        declared.extend(declared_of(&a.name, &a.ore.declarations));
        let g = generated_in(Some(&a.host), &a.name, &a.ore);
        generated.extend(g.callbacks.into_iter().map(|(_, d)| d));
        undecided.extend(g.undecided);
        for e in &a.ore.declarations {
            if let Declaration::Association(assoc) = &e.decl {
                if assoc.kind == AssocKind::HasAndBelongsToMany {
                    habtm.insert(assoc.name.clone());
                }
            }
        }
    }
    let mut modules = Vec::new();
    let mut order_unknown_scopes = BTreeSet::new();
    let mut order_hidden = Vec::new();
    for a in ancestors.iter().filter(|a| a.ore.kind == OreKind::Module) {
        let included_decls = a
            .ore
            .declarations
            .iter()
            .filter(|d| matches!(d.origin, DeclOrigin::Included { .. }))
            .count();
        let unharvested = unharvested_counts(&a.ore);
        let completeness = match (included_decls > 0, unharvested.is_empty()) {
            (true, true) => Completeness::Full,
            (true, false) => Completeness::Partial,
            (false, false) => Completeness::Unread,
            (false, true) => Completeness::NoIncludeTimeBody,
        };
        // A statement that may hide a registration makes the scope
        // order-unknown unless it is a conditional whose skipped branches ruff
        // read in full (`Unharvested::hidden_complete`, ruff
        // `crates/ruff_ruby_spo/src/events.rs`) and whose `hidden` list is
        // nameable: then `hidden` is everything the branches could register,
        // so it feeds `order_hidden` (which can make OTHER groups unknown) and
        // leaves this scope's own groups definite. An incomplete conditional
        // keeps the old rule: `hidden` is only a lower bound there. This runs
        // for every module-like ancestor, expanded macro bodies included
        // (`visit_run` pushes them as module ancestors; their `unharvested`
        // are ruff's `MacroStep::Unread` statements, `hidden_unread` intact).
        let mut unknown = false;
        for u in a
            .ore
            .unharvested
            .iter()
            .filter(|u| hides_registration(u.reason))
        {
            if let Some(named) = hidden_registrations(u, &a.name, &a.host) {
                order_hidden.extend(named);
            }
            if makes_order_unknown(u, &a.name, &a.host) {
                unknown = true;
            }
        }
        if unknown {
            order_unknown_scopes.insert(a.name.clone());
        }
        modules.push(ModuleRead {
            name: a.name.clone(),
            file: a.file.clone(),
            included_decls,
            unharvested,
            completeness,
            is_patch: patch_names.contains(a.name.as_str()),
        });
    }
    ModelCtx {
        modules,
        order_unknown_scopes,
        order_hidden,
        has_file,
        assocs: association_names(ancestors),
        ancestor_files: ancestors.iter().map(|a| a.file.clone()).collect(),
        declared,
        generated,
        undecided,
        habtm,
        effective,
    }
}
