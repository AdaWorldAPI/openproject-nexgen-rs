pub fn join_rel(base: &str, seg: &str) -> String {
    if base.is_empty() {
        seg.to_string()
    } else {
        format!("{base}/{seg}")
    }
}

/// Directories matching `pattern` (a `*` segment is one directory).
pub fn expand_dirs(src: &Path, pattern: &str) -> Vec<String> {
    let mut cur = vec![String::new()];
    for seg in pattern.split('/') {
        let mut next = Vec::new();
        for base in &cur {
            if seg == "*" {
                let mut names: Vec<String> = std::fs::read_dir(src.join(base))
                    .into_iter()
                    .flatten()
                    .flatten()
                    .filter(|e| e.path().is_dir())
                    .map(|e| e.file_name().to_string_lossy().to_string())
                    .collect();
                names.sort();
                next.extend(names.iter().map(|n| join_rel(base, n)));
            } else {
                next.push(join_rel(base, seg));
            }
        }
        cur = next;
    }
    cur.into_iter().filter(|d| src.join(d).is_dir()).collect()
}

pub fn files_named(src: &Path, dir: &str, name: &str, out: &mut Vec<String>) {
    let mut entries: Vec<_> = std::fs::read_dir(src.join(dir))
        .into_iter()
        .flatten()
        .flatten()
        .collect();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for e in entries {
        let n = e.file_name().to_string_lossy().to_string();
        let rel = join_rel(dir, &n);
        if e.path().is_dir() {
            files_named(src, &rel, name, out);
        } else if n == name {
            out.push(rel);
        }
    }
}

/// Every `.rb` under `dir`, recursively, in name order, skipping `test` and
/// `spec` directories.
pub fn rb_files(src: &Path, dir: &str, out: &mut Vec<String>) {
    let mut entries: Vec<_> = std::fs::read_dir(src.join(dir))
        .into_iter()
        .flatten()
        .flatten()
        .collect();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for e in entries {
        let n = e.file_name().to_string_lossy().to_string();
        let rel = join_rel(dir, &n);
        if e.path().is_dir() {
            if !matches!(n.as_str(), "test" | "spec") {
                rb_files(src, &rel, out);
            }
        } else if n.ends_with(".rb") {
            out.push(rel);
        }
    }
}

/// Module directories in the order `file` lists them.
pub fn engine_order(src: &Path, cfg: &EngineOrderCfg) -> Vec<String> {
    let text = std::fs::read_to_string(src.join(&cfg.file)).unwrap_or_default();
    let mut out = Vec::new();
    for line in text.lines() {
        if let Some((_, rest)) = line.split_once(cfg.line_marker.as_str()) {
            if let Some((name, _)) = rest.split_once(cfg.line_marker_end.as_str()) {
                out.push(name.to_string());
            }
        }
    }
    out
}

/// `[:A,:B]` -> `["A", "B"]`.
pub fn parse_symbol_array(args: &str) -> Option<Vec<String>> {
    let inner = args.trim().strip_prefix('[')?.strip_suffix(']')?;
    inner
        .split(',')
        .map(|t| t.trim().strip_prefix(':').map(str::to_string))
        .collect()
}

/// `:A, :B` -> `["A", "B"]`.
pub fn parse_symbol_path(args: &str) -> Option<Vec<String>> {
    args.split(',')
        .map(|t| t.trim().strip_prefix(':').map(str::to_string))
        .collect()
}

/// `"Mod", <rest>` -> (`Mod`, targets in `rest`). Ruff renders keyword
/// arguments it does not know as `<expr>`; with no readable target the result
/// is `Err`.
pub fn parse_module_into(args: &str) -> Result<(String, Vec<String>), String> {
    let rest = args
        .trim()
        .strip_prefix('"')
        .ok_or("first argument is not a string")?;
    let (module, rest) = rest.split_once('"').ok_or("unterminated module string")?;
    if rest.contains("<expr>") {
        return Err("ruff renders the `into:` keyword argument as <expr>".into());
    }
    let targets: Vec<String> = rest
        .split('"')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect();
    if targets.is_empty() {
        return Err("no `into:` target in the rendered arguments".into());
    }
    Ok((module.to_string(), targets))
}

pub fn fill(template: &str, vars: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (k, v) in vars {
        out = out.replace(&format!("{{{k}}}"), v);
    }
    out
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum How {
    Include,
    Prepend,
}

/// A patch the intake resolved to a file in the roots.
#[derive(Debug, Clone)]
pub struct AppliedPatch {
    pub module_dir: String,
    pub engine: String,
    pub call: String,
    pub seq: u32,
    pub target: String,
    pub how: How,
    pub patch_name: String,
    pub patch_file: String,
    pub cite: String,
}

/// Why a patch call has no (readable) patch module. Closed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum PatchSlag {
    /// The call's arguments do not have the shape the rule expects.
    ArgsUnreadable,
    /// The call names a patch module but ruff renders its target (`into:`) as
    /// `<expr>`. Stage: ruff extension (render keyword arguments in
    /// `walk::render_node`, which today handles `Hash` and not `Kwargs`).
    TargetUnreadable,
    /// No file in the roots defines the module the rule derives.
    PatchFileNotFound,
    /// The module's file exists, but it registers its declarations in
    /// `def self.included(base) ... base.class_eval do ... end`, which
    /// `module_ore` does not walk (only a direct `included do`). Stage: ruff
    /// extension (walk `base.class_eval` bodies inside `self.included`).
    ///
    /// Since ruff #156 the hook is read; this reason now means the module has
    /// an include-time body (`included do`, `def self.included`) and NOT ONE
    /// declaration came out of it, while `ClassOre::unharvested` lists
    /// statements it could not read (or the file still has a hook whose body
    /// produced nothing).
    BodyUnreadable,
    /// The module's include-time bodies yielded at least one declaration AND
    /// `ClassOre::unharvested` lists at least one statement that produced none
    /// (conditional, `def`, other receiver, dynamic send, unread block body).
    /// The module is applied with what was read; the unread statements may
    /// register more. Stage: ruff extension for the listed reasons. A module
    /// whose include-time bodies were read in full is not slag.
    BodyPartiallyRead,
}

impl PatchSlag {
    /// The reasons that annotate a patch that WAS applied. Every other reason
    /// means the (call, target) job was not applied.
    pub fn is_applied_with_note(self) -> bool {
        matches!(
            self,
            PatchSlag::BodyUnreadable | PatchSlag::BodyPartiallyRead
        )
    }

    pub fn all() -> &'static [PatchSlag] {
        &[
            PatchSlag::ArgsUnreadable,
            PatchSlag::TargetUnreadable,
            PatchSlag::PatchFileNotFound,
            PatchSlag::BodyUnreadable,
            PatchSlag::BodyPartiallyRead,
        ]
    }
}

#[derive(Debug, Clone)]
pub struct PatchUnresolved {
    pub reason: PatchSlag,
    pub engine: String,
    pub call: String,
    /// Statement ordinal of the call in the engine body.
    pub seq: u32,
    /// The `into:` / symbol target this entry is about. `None` when the call
    /// failed before any target was known (`ArgsUnreadable`, `TargetUnreadable`).
    pub target: Option<String>,
    pub detail: String,
    /// For `BodyUnreadable` / `BodyPartiallyRead`: the module's unharvested
    /// statements per `UnharvestedReason::as_str`.
    pub unharvested: BTreeMap<String, usize>,
}

/// One unit of patch work: a rule-matched call and one of its targets (a call
/// whose targets cannot be read is one job with `target: None`). Every job ends
/// in exactly one of: an [`AppliedPatch`], or one [`PatchUnresolved`] whose
/// reason is not [`PatchSlag::is_applied_with_note`].
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct PatchJob {
    pub engine: String,
    pub call: String,
    pub seq: u32,
    pub target: Option<String>,
}

#[derive(Default)]
pub struct PatchIntake {
    pub engines: usize,
    /// Calls matched by a rule.
    pub calls: usize,
    /// One entry per (call, target): `calls` counts a call once however many
    /// targets it names, so conservation is checked over these.
    pub jobs: Vec<PatchJob>,
    pub applied: Vec<AppliedPatch>,
    pub unresolved: Vec<PatchUnresolved>,
}

impl PatchIntake {
    pub fn for_model<'a>(&'a self, model: &'a str) -> impl Iterator<Item = &'a AppliedPatch> {
        self.applied.iter().filter(move |p| p.target == model)
    }
}

/// A module's unharvested include-time statements, counted per reason.
pub fn unharvested_counts(ore: &ClassOre) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for u in &ore.unharvested {
        *out.entry(u.reason.as_str().to_string()).or_insert(0) += 1;
    }
    out
}

/// Statements that may hide a callback registration: control flow (a branch
/// may register), a dynamic `send`, a block body ruff did not read. The other
/// reasons (a `def`, a call on another receiver, an unrecognised call) are
/// counted and shown, but do not make the order unknown. Whether the hiding
/// statement makes the scope order-unknown is [`makes_order_unknown`]: a
/// control-flow statement whose branches ruff read in full does not.
pub fn hides_registration(r: UnharvestedReason) -> bool {
    matches!(
        r,
        UnharvestedReason::ControlFlow
            | UnharvestedReason::DynamicSend
            | UnharvestedReason::UnreadBlockBody
    )
}

/// Whether `u` makes the scope that holds it order-unknown. A dynamic `send`
/// and an unread block body always do. A control-flow statement does unless
/// ruff read every statement of its skipped branches
/// (`Unharvested::hidden_complete`) AND `hidden_registrations` can name all of
/// them (an `include` or a macro in a branch cannot be derived here); then
/// `hidden` is exhaustive and goes to [`ModelCtx::order_hidden`] instead.
pub fn makes_order_unknown(
    u: &ruff_ruby_spo::events::Unharvested,
    scope: &str,
    host: &str,
) -> bool {
    if !hides_registration(u.reason) {
        return false;
    }
    if u.reason != UnharvestedReason::ControlFlow {
        return true;
    }
    !(u.hidden_complete() && hidden_registrations(u, scope, host).is_some())
}

pub fn discover_patches(src: &Path, cfg: &IntakeCfg, h: &mut Harvest) -> PatchIntake {
    let order = engine_order(src, &cfg.engine_order);
    let rank = |dir: &str| order.iter().position(|d| d == dir).unwrap_or(order.len());
    let mut files = Vec::new();
    for pat in &cfg.engines.search {
        for dir in expand_dirs(src, pat) {
            files_named(src, &dir, &cfg.engines.file_name, &mut files);
        }
    }
    let mut out = PatchIntake::default();
    let mut found: Vec<(usize, AppliedPatch)> = Vec::new();
    for file in files {
        let module_dir = file.split('/').nth(1).unwrap_or_default().to_string();
        let text = std::fs::read_to_string(src.join(&file)).unwrap_or_default();
        let mut syms = Symbols::default();
        for ore in source_ore_from(&file, &text, "op", &mut syms) {
            if !ore
                .superclass
                .as_deref()
                .is_some_and(|s| cfg.engines.superclass.iter().any(|c| c == s))
            {
                continue;
            }
            out.engines += 1;
            let plugin_module = ore
                .name
                .rsplit_once("::")
                .map(|(m, _)| m.to_string())
                .unwrap_or_default();
            for e in &ore.declarations {
                let Declaration::DslCall(call) = &e.decl else {
                    continue;
                };
                let Some(rule) = cfg.patch_rules.iter().find(|r| r.call == call.name) else {
                    continue;
                };
                out.calls += 1;
                let fail = |reason, target: Option<&str>, detail: String| PatchUnresolved {
                    reason,
                    engine: ore.name.clone(),
                    call: format!("{} {}", call.name, call.args),
                    seq: e.seq,
                    target: target.map(str::to_string),
                    detail,
                    unharvested: BTreeMap::new(),
                };
                // A call that fails before its targets are known is one job
                // with no target; otherwise there is one job per target.
                let job = |target: Option<&str>| PatchJob {
                    engine: ore.name.clone(),
                    call: call.name.clone(),
                    seq: e.seq,
                    target: target.map(str::to_string),
                };
                // (target, vars for the patch name templates)
                let mut jobs: Vec<(String, Vec<(&str, String)>)> = Vec::new();
                match rule.args.as_str() {
                    "symbol_array" => match parse_symbol_array(&call.args) {
                        Some(names) => {
                            for n in names {
                                jobs.push((
                                    n.clone(),
                                    vec![("class", n.clone()), ("qualified", n)],
                                ));
                            }
                        }
                        None => {
                            out.jobs.push(job(None));
                            out.unresolved.push(fail(
                                PatchSlag::ArgsUnreadable,
                                None,
                                "not a symbol array".into(),
                            ));
                            continue;
                        }
                    },
                    "symbol_path" => match parse_symbol_path(&call.args) {
                        Some(path) if !path.is_empty() => {
                            let class = path[path.len() - 1].clone();
                            let qualified = path.join("::");
                            jobs.push((
                                qualified.clone(),
                                vec![("class", class), ("qualified", qualified)],
                            ));
                        }
                        _ => {
                            out.jobs.push(job(None));
                            out.unresolved.push(fail(
                                PatchSlag::ArgsUnreadable,
                                None,
                                "not a symbol path".into(),
                            ));
                            continue;
                        }
                    },
                    "module_into" => match parse_module_into(&call.args) {
                        Ok((module, targets)) => {
                            for t in targets {
                                jobs.push((t, vec![("module", module.clone())]));
                            }
                        }
                        Err(why) => {
                            let reason = if why.starts_with("ruff") || why.starts_with("no `into") {
                                PatchSlag::TargetUnreadable
                            } else {
                                PatchSlag::ArgsUnreadable
                            };
                            out.jobs.push(job(None));
                            out.unresolved.push(fail(reason, None, why));
                            continue;
                        }
                    },
                    other => panic!("intake.json: unknown args form {other:?}"),
                }
                let how = match rule.how.as_str() {
                    "include" => How::Include,
                    "prepend" => How::Prepend,
                    other => panic!("intake.json: unknown how {other:?}"),
                };
                for (target, vars) in jobs {
                    out.jobs.push(job(Some(&target)));
                    let mut vars: Vec<(&str, &str)> =
                        vars.iter().map(|(k, v)| (*k, v.as_str())).collect();
                    vars.push(("plugin_module", plugin_module.as_str()));
                    let hit = rule.patch.iter().find_map(|t| {
                        let name = fill(t, &vars);
                        h.find(&name).map(|(file, ore)| (name, file, ore))
                    });
                    let Some((patch_name, patch_file, patch_ore)) = hit else {
                        out.unresolved.push(fail(
                            PatchSlag::PatchFileNotFound,
                            Some(&target),
                            format!("target {target}: none of {:?} in the roots", rule.patch),
                        ));
                        continue;
                    };
                    let reads_included_block = patch_ore
                        .declarations
                        .iter()
                        .any(|d| matches!(d.origin, DeclOrigin::Included { .. }));
                    let unread = unharvested_counts(&patch_ore);
                    // The scan only picks the reason; the module is applied either way.
                    let legacy_hook = std::fs::read_to_string(src.join(&patch_file))
                        .is_ok_and(|t| t.contains("def self.included"));
                    // Nothing recovered from an include-time body that exists
                    // (a hook the file has, or statements ruff lists as unread)
                    // is `BodyUnreadable`; something recovered next to a
                    // non-empty `unharvested` list is `BodyPartiallyRead`; an
                    // empty list with declarations is a full read, not slag.
                    let note = if how != How::Include {
                        None
                    } else if !reads_included_block && (legacy_hook || !unread.is_empty()) {
                        Some(PatchSlag::BodyUnreadable)
                    } else if reads_included_block && !unread.is_empty() {
                        Some(PatchSlag::BodyPartiallyRead)
                    } else {
                        None
                    };
                    if let Some(reason) = note {
                        let mut u = fail(
                            reason,
                            Some(&target),
                            format!("target {target}: {patch_name} in {patch_file}"),
                        );
                        u.unharvested = unread;
                        out.unresolved.push(u);
                    }
                    found.push((
                        rank(&module_dir),
                        AppliedPatch {
                            module_dir: module_dir.clone(),
                            engine: ore.name.clone(),
                            call: call.name.clone(),
                            seq: e.seq,
                            target,
                            how,
                            patch_name,
                            patch_file,
                            cite: rule.cite.clone(),
                        },
                    ));
                }
            }
        }
    }
    // to_prepare order: engine (gem require) order, then statement order.
    found.sort_by(|(ra, a), (rb, b)| (ra, &a.module_dir, a.seq).cmp(&(rb, &b.module_dir, b.seq)));
    out.applied = found.into_iter().map(|(_, p)| p).collect();
    out
}

