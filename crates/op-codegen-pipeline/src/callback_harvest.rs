pub const VALIDATES_COMMON_OPTIONS: &[&str] = &[
    "allow_nil",
    "allow_blank",
    "if",
    "unless",
    "on",
    "message",
    "strict",
    "prepend",
];

/// `before_validation` -> (`before`, `validation`); `after_create_commit` ->
/// (`after`, `commit`, implied `create`).
pub fn split_phase(phase: &str) -> Option<(String, String, Option<&'static str>)> {
    let (kind, rest) = phase.split_once('_')?;
    if !matches!(kind, "before" | "after" | "around") {
        return None;
    }
    let (chain, implied) = match rest {
        "create_commit" => ("commit", Some("create")),
        "update_commit" => ("commit", Some("update")),
        "destroy_commit" => ("commit", Some("destroy")),
        "save_commit" => ("commit", Some("save")),
        other => (other, None),
    };
    Some((kind.to_string(), chain.to_string(), implied))
}

pub fn declared_of(origin: &str, events: &[RailsEvent]) -> Vec<Declared> {
    let mut out = Vec::new();
    for d in events.iter().map(|e| &e.decl) {
        match d {
            Declaration::Callback(cb) => {
                let Some((kind, chain, implied_on)) = split_phase(&cb.phase) else {
                    continue;
                };
                let filter = if cb.target.starts_with('<') {
                    Filter::Block
                } else {
                    Filter::Method(cb.target.clone())
                };
                out.push(Declared {
                    chain,
                    kind,
                    filter,
                    origin: origin.to_string(),
                    options: cb.options.clone(),
                    implied_on,
                    generated: None,
                });
            }
            Declaration::Validation(v) => {
                let (filter, ok) = match v.kind {
                    ValidationKind::Validate => (
                        if v.target.starts_with('<') {
                            Filter::Block
                        } else {
                            Filter::Method(v.target.clone())
                        },
                        true,
                    ),
                    ValidationKind::ValidatesWith => {
                        (Filter::ValidatesWith(v.target.clone()), true)
                    }
                    ValidationKind::ValidatesEach => (Filter::Block, true),
                    ValidationKind::Validates => {
                        // One entry per validator kind named in the options.
                        for (k, _) in &v.options {
                            if VALIDATES_COMMON_OPTIONS.contains(&k.as_str()) {
                                continue;
                            }
                            out.push(Declared {
                                chain: "validate".into(),
                                kind: "before".into(),
                                filter: Filter::Validator {
                                    kind: k.clone(),
                                    attr: v.target.clone(),
                                },
                                origin: origin.to_string(),
                                options: v.options.clone(),
                                implied_on: None,
                                generated: None,
                            });
                        }
                        (Filter::Block, false)
                    }
                    ValidationKind::ValidatesAssociated | ValidationKind::Normalizes => {
                        (Filter::Block, false)
                    }
                };
                if ok {
                    out.push(Declared {
                        chain: "validate".into(),
                        kind: "before".into(),
                        filter,
                        origin: origin.to_string(),
                        options: v.options.clone(),
                        implied_on: None,
                        generated: None,
                    });
                }
            }
            _ => {}
        }
    }
    out
}

/// What `rails_generated` returns for one ancestor, as matchable callbacks, plus
/// the rules it could not decide.
pub struct GeneratedOf {
    /// Each generated callback with the seq of the declaration that caused it.
    pub callbacks: Vec<(u32, Declared)>,
    pub undecided: Vec<UndecidedRow>,
}

#[derive(Debug, Clone)]
pub struct UndecidedRow {
    pub origin: String,
    pub association: String,
    pub rule: String,
    pub reason: String,
}

pub fn generated_of(origin: &str, ore: &ClassOre) -> GeneratedOf {
    generated_in(None, origin, ore)
}

/// [`generated_of`] for a body whose macros run in the class `host`. Needed to
/// name the middle association of a `has_and_belongs_to_many`; with no host the
/// rule stays undecided.
pub fn generated_in(host: Option<&str>, origin: &str, ore: &ClassOre) -> GeneratedOf {
    generated_from(host, origin, &ore.declarations)
}

/// [`generated_in`] for a list of events that is not a whole body (the
/// declarations a skipped branch holds).
pub fn generated_from(host: Option<&str>, origin: &str, events: &[RailsEvent]) -> GeneratedOf {
    let mut out = GeneratedOf {
        callbacks: Vec::new(),
        undecided: Vec::new(),
    };
    let derived = derive_in(host, events, OP_RAILS_DEFAULTS);
    for g in derived {
        match g {
            Generated::Callback(cb) => {
                let chain = match cb.chain {
                    GenChain::Save => "save",
                    GenChain::Create => "create",
                    GenChain::Update => "update",
                    GenChain::Validate => "validate",
                    GenChain::Validation => "validation",
                };
                let kind = match cb.kind {
                    GenKind::Before => "before",
                    GenKind::After => "after",
                    GenKind::Around => "around",
                };
                let filter = match cb.filter {
                    GenFilter::Method(m) => Filter::Method(m),
                    GenFilter::PresenceValidator { attribute } => Filter::Validator {
                        kind: "presence".into(),
                        attr: attribute,
                    },
                };
                out.callbacks.push((
                    cb.origin.declaration_seq,
                    Declared {
                        chain: chain.into(),
                        kind: kind.into(),
                        filter,
                        origin: origin.to_string(),
                        options: cb.options,
                        implied_on: None,
                        generated: Some(GeneratedFrom {
                            association: cb.association,
                            rule: cb.origin.rule,
                        }),
                    },
                ));
            }
            Generated::Undecided(u) => out.undecided.push(UndecidedRow {
                origin: origin.to_string(),
                association: u.association,
                rule: u.rule,
                reason: u.reason,
            }),
        }
    }
    out
}

pub fn association_names(ancestors: &[Ancestor]) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for a in ancestors {
        for d in a.ore.declarations.iter().map(|e| &e.decl) {
            if let Declaration::Association(assoc) = d {
                if matches!(
                    assoc.kind,
                    AssocKind::BelongsTo
                        | AssocKind::HasMany
                        | AssocKind::HasOne
                        | AssocKind::HasAndBelongsToMany
                ) {
                    out.insert(assoc.name.clone());
                }
            }
        }
    }
    out
}

// ─────────────────────────────────────────────────────────────────────────
// Class-level macros
// ─────────────────────────────────────────────────────────────────────────
//
// `acts_as_attachable order: ...` is a method call in a class body; what it
// registers is in the body of the method it calls. `macros.rules` in
// `oracle/intake.json` says which call runs which `def`; ruff reads the `def`
// as a macro (`events::macro_ore_from`): the declarations it makes, in order,
// the modules it includes, and the other modules it hands the class to. This
// code splices those declarations in where the call is. No macro name and no
// registration is written in Rust, and nothing is evaluated: a statement ruff
// cannot read is listed as unread, never assumed.

/// The keyword options of a macro call that a `**<param>` splat inside the
/// macro body passes on, as `(key, rendered value)`.
pub type CallOptions = [(String, String)];

/// Replace each `**splat` of `assoc` by the options it stands for, when the
/// splat is the macro's own options parameter (`**options`), possibly merged
/// with a literal hash (`**options.reverse_merge!(as: :container)`,
/// `.merge(...)`), and the call's options are known. Any other splat stays:
/// the association's rules then report it undecided, as before.
///
/// The key SET is what the rules read (`validate`, `autosave`, `required`,
/// `optional`), so a key the macro deletes from its options
/// (`options.delete(:order)`) is still counted as given. That can only add a
/// key, never hide one: a rule that sees too many keys is undecided or reads
/// the caller's literal value, it never skips a validation.
pub fn resolve_splats(assoc: &mut AssocDecl, param: &str, call: Option<&CallOptions>) {
    let Some(call) = call else { return };
    if assoc.option_splats.is_empty() {
        return;
    }
    let original = std::mem::take(&mut assoc.options);
    let mut splats = std::mem::take(&mut assoc.option_splats);
    splats.sort_by_key(|s| s.before);
    let mut options: Vec<(String, String)> = Vec::new();
    let mut remaining: Vec<OptionSplat> = Vec::new();
    let mut at = 0usize;
    for splat in splats {
        while at < splat.before.min(original.len()) {
            options.push(original[at].clone());
            at += 1;
        }
        match resolve_splat(&splat.source, param, call) {
            Some(pairs) => options.extend(pairs),
            None => remaining.push(OptionSplat {
                source: splat.source,
                before: options.len(),
            }),
        }
    }
    options.extend(original[at..].iter().cloned());
    assoc.options = options;
    assoc.option_splats = remaining;
}

/// `**options`, `**options.reverse_merge!(k: v, ...)`, `**options.merge(k: v)`.
/// `reverse_merge` keeps the receiver's value where both give a key, `merge`
/// the argument's; the later pair wins in the result, as in a hash literal.
fn resolve_splat(source: &str, param: &str, call: &CallOptions) -> Option<Vec<(String, String)>> {
    let rest = source.trim().strip_prefix("**")?.strip_prefix(param)?;
    if rest.is_empty() {
        return Some(call.to_vec());
    }
    let (method, inner) = rest.strip_prefix('.')?.split_once('(')?;
    let inner = inner.strip_suffix(')')?;
    let extra = literal_pairs(inner)?;
    match method {
        "reverse_merge" | "reverse_merge!" => {
            let mut out = extra;
            out.extend(call.iter().cloned());
            Some(out)
        }
        "merge" | "merge!" => {
            let mut out = call.to_vec();
            out.extend(extra);
            Some(out)
        }
        _ => None,
    }
}

/// `k: v, k2: v2` (optionally inside braces) as pairs, in order. `None` when
/// any element is not a `key: value` pair with a plain key.
fn literal_pairs(text: &str) -> Option<Vec<(String, String)>> {
    let text = text.trim();
    let text = text
        .strip_prefix('{')
        .and_then(|t| t.strip_suffix('}'))
        .unwrap_or(text);
    let mut parts: Vec<String> = Vec::new();
    let (mut depth, mut cur) = (0i32, String::new());
    let mut quote: Option<char> = None;
    for c in text.chars() {
        match (quote, c) {
            (Some(q), c) if c == q => {
                quote = None;
                cur.push(c);
            }
            (Some(_), c) => cur.push(c),
            (None, '"' | '\'') => {
                quote = Some(c);
                cur.push(c);
            }
            (None, '(' | '[' | '{') => {
                depth += 1;
                cur.push(c);
            }
            (None, ')' | ']' | '}') => {
                depth -= 1;
                if depth < 0 {
                    // A closer with no opener: this is not one hash's pairs
                    // (`as: :a).merge(x: 1`), so it is not read.
                    return None;
                }
                cur.push(c);
            }
            (None, ',') if depth == 0 => parts.push(std::mem::take(&mut cur)),
            (None, c) => cur.push(c),
        }
    }
    if depth != 0 || quote.is_some() {
        return None;
    }
    if !cur.trim().is_empty() {
        parts.push(cur);
    }
    parts
        .iter()
        .map(|p| {
            let (k, v) = p.trim().split_once(':')?;
            let k = k.trim();
            (!k.is_empty() && k.chars().all(|c| c.is_alphanumeric() || c == '_'))
                .then(|| (k.to_string(), v.trim().to_string()))
        })
        .collect()
}

/// The argument text of the call that starts at byte `anchor` of `text`, with
/// comments removed: the balanced `( ... )` when the name is followed by `(`,
/// otherwise the rest of the statement (to a `;`, or a newline that does not
/// continue the argument list with a trailing `,` or `\`). `None` when
/// `anchor` is not a position in `text` or the parentheses are not closed.
pub fn call_arg_text(text: &str, anchor: usize) -> Option<String> {
    let rest = text.get(anchor..)?;
    let name_len = rest
        .find(|c: char| !(c.is_alphanumeric() || c == '_'))
        .unwrap_or(rest.len());
    let after = &rest[name_len..];
    let (parens, body) = match after.strip_prefix('(') {
        Some(body) => (true, body),
        None => (false, after),
    };
    let (mut quote, mut comment) = (None::<char>, false);
    let mut depth = 1i32;
    let mut out = String::new();
    // The last significant character so far, comments excluded: a line that
    // ends in `,` or `\` continues onto the next one.
    let mut last = ' ';
    for c in body.chars() {
        if comment {
            if c == '\n' {
                comment = false;
            } else {
                continue;
            }
        }
        match (quote, c) {
            (Some(q), c) if c == q => quote = None,
            (Some(_), _) => {}
            (None, '"' | '\'') => quote = Some(c),
            (None, '#') => {
                comment = true;
                continue;
            }
            (None, '(' | '[' | '{') if parens => depth += 1,
            (None, ')' | ']' | '}') if parens => {
                depth -= 1;
                if depth == 0 {
                    return Some(out);
                }
            }
            (None, ';') if !parens => return Some(out.trim().to_string()),
            (None, '\n') if !parens && !matches!(last, ',' | '\\') => {
                return Some(out.trim().to_string())
            }
            _ => {}
        }
        if quote.is_some() || !c.is_whitespace() {
            last = c;
        }
        out.push(c);
    }
    (!parens).then(|| out.trim().to_string())
}

/// An expanded macro body, ready to be walked like a module body.
pub struct MacroRun {
    /// The module or class whose `def` this is: the lexical scope its
    /// constants resolve in.
    pub owner: String,
    pub file: String,
    pub ore: ClassOre,
}

/// How many macro bodies may call each other before the walk stops.
const MACRO_DEPTH: usize = 4;

impl Harvest {
    /// The macros the class-body declarations of `ore` call, expanded, for the
    /// statements that run in the including class.
    pub fn macro_runs_of(&mut self, ore: &ClassOre) -> Vec<MacroRun> {
        let mut out = Vec::new();
        for e in &ore.declarations {
            if ore.kind == OreKind::Class || matches!(e.origin, DeclOrigin::Included { .. }) {
                out.extend(self.macro_runs_of_decl(e, &ore.file));
            }
        }
        out
    }

    /// The keyword options of the `acts_as_*` call `e` (written in `file`) when
    /// the call's source passes literal `key: value` pairs and nothing else.
    ///
    /// `ActsAs::options` is built by ruff's `hash_pairs`, which drops a
    /// `**splat` and takes the first hash argument only, so `acts_as_x **opts`,
    /// `acts_as_x(some_hash)` and `acts_as_x a: 1, **more` all look like known
    /// options. ruff exposes no argument text for `ActsAs`, so the call is
    /// re-read from `file` at the event's anchor; any unreadable file, anchor
    /// or argument form is `None` (undecided), never an empty key set.
    fn acts_as_call_options(&self, e: &RailsEvent, file: &str) -> Option<Vec<(String, String)>> {
        let text = std::fs::read_to_string(self.src.join(file)).ok()?;
        literal_pairs(&call_arg_text(&text, e.anchor as usize)?)
    }

    /// The expansion of one declaration, empty when it is not a call of a
    /// macro the intake knows.
    pub fn macro_runs_of_decl(&mut self, e: &RailsEvent, file: &str) -> Vec<MacroRun> {
        let decl = &e.decl;
        let (dsl, options): (String, Option<Vec<(String, String)>>) = match decl {
            Declaration::ActsAs(a) => (
                format!("acts_as_{}", a.variant),
                self.acts_as_call_options(e, file),
            ),
            Declaration::GemDsl(g) => (underscore(&format!("{:?}", g.gem)), None),
            Declaration::DslCall(c) => (c.name.clone(), None),
            _ => return Vec::new(),
        };
        if !self.macros_enabled {
            return Vec::new();
        }
        let Some(rule) = self.macros.iter().find(|r| r.dsl == dsl).cloned() else {
            return Vec::new();
        };
        let mut out = Vec::new();
        self.expand_def(
            &rule.file,
            &rule.def_name,
            None,
            options.as_deref(),
            0,
            &mut out,
        );
        out
    }

    /// The body of the `def` that creates a macro-defined class, read through
    /// the local that holds the new class, as one run.
    pub fn defined_class_run(&mut self, def: &MacroDefine) -> Option<MacroRun> {
        let Some(file) = resolve_glob_file(&self.src, &def.file) else {
            self.macro_log.push(format!(
                "{}: {} is not in the checkout",
                def.class, def.file
            ));
            return None;
        };
        let text = std::fs::read_to_string(self.src.join(&file)).unwrap_or_default();
        let m = macro_ore_local_from(&file, &text, &def.def_name, &def.local)
            .into_iter()
            .next()?;
        let label = format!("{}#{}", m.owner, m.name);
        let declarations: Vec<RailsEvent> = m.declarations.clone();
        let unharvested = m
            .steps
            .iter()
            .filter_map(|s| match s {
                MacroStep::Unread(u) => Some(u.clone()),
                _ => None,
            })
            .collect();
        Some(MacroRun {
            owner: label.clone(),
            file: file.clone(),
            ore: ClassOre {
                iri: format!("op:{label}"),
                name: label,
                declarations,
                methods: Vec::new(),
                kind: OreKind::Module,
                file,
                includes: Vec::new(),
                superclass: None,
                unharvested,
            },
        })
    }

    /// The registration order of a class a macro defines: its superclass chain,
    /// then what the macro registers on it.
    pub fn effective_defined(
        &mut self,
        model: &str,
        superclass: &str,
        run: &MacroRun,
    ) -> Vec<Declared> {
        let mut st = EffState {
            included: BTreeSet::new(),
            out: Vec::new(),
            host: model.to_string(),
        };
        let mut guard = BTreeSet::new();
        self.eff_class(superclass, &mut st, &mut guard);
        st.host = model.to_string();
        self.eff_body(&run.owner, &run.ore, false, &mut st);
        st.out
    }

    /// Read `def <def_name>` of `file_pattern` as a macro and append what it
    /// registers, in order: declarations as one run, each hand-over of the
    /// class (`Module.method(.., self, ..)`) and each call of another method
    /// of the same file as the runs of that method, in place.
    fn expand_def(
        &mut self,
        file_pattern: &str,
        def_name: &str,
        class_arg: Option<usize>,
        call: Option<&CallOptions>,
        depth: usize,
        out: &mut Vec<MacroRun>,
    ) {
        let Some(file) = resolve_glob_file(&self.src, file_pattern) else {
            self.macro_log
                .push(format!("{def_name}: {file_pattern} is not in the checkout"));
            return;
        };
        let text = std::fs::read_to_string(self.src.join(&file)).unwrap_or_default();
        let Some(m) = macro_ore_from(&file, &text, def_name, class_arg)
            .into_iter()
            .next()
        else {
            self.macro_log
                .push(format!("{def_name}: no `def {def_name}` in {file}"));
            return;
        };
        let param = m.params.first().cloned().unwrap_or_default();
        let mut chunk: Vec<RailsEvent> = Vec::new();
        let mut unread = Vec::new();
        let mut hides = 0usize;
        let (mut decls, mut delegates, mut calls) = (0usize, 0usize, 0usize);
        let mut first = true;
        let flush = |chunk: &mut Vec<RailsEvent>,
                     unread: &mut Vec<ruff_ruby_spo::events::Unharvested>,
                     out: &mut Vec<MacroRun>,
                     force: bool| {
            if chunk.is_empty() && !(force && !unread.is_empty()) {
                return;
            }
            let declarations: Vec<RailsEvent> = std::mem::take(chunk)
                .into_iter()
                .enumerate()
                .map(|(i, mut e)| {
                    e.seq = u32::try_from(i).unwrap_or(u32::MAX);
                    e
                })
                .collect();
            // `Owner#def`: one scope per macro method, so what one method
            // leaves unread does not make another's order unknown. A constant
            // resolves from `Owner#def` as from `Owner`: the last segment
            // matches nothing and is dropped.
            let label = format!("{}#{}", m.owner, m.name);
            out.push(MacroRun {
                owner: label.clone(),
                file: file.clone(),
                ore: ClassOre {
                    iri: format!("op:{label}"),
                    name: label,
                    declarations,
                    methods: Vec::new(),
                    kind: OreKind::Module,
                    file: file.clone(),
                    includes: Vec::new(),
                    superclass: None,
                    // The statements this def left unread, once, on its first run.
                    unharvested: std::mem::take(unread),
                },
            });
        };
        for step in &m.steps {
            match step {
                MacroStep::Decl(i) => {
                    let mut e = m.declarations[*i as usize].clone();
                    if let Declaration::DslCall(c) = &e.decl {
                        // A call of another method of this same file
                        // (`include_aaj_modules`): its body runs here.
                        if depth < MACRO_DEPTH
                            && c.name != def_name
                            && !macro_ore_from(&file, &text, &c.name, None).is_empty()
                        {
                            calls += 1;
                            flush(&mut chunk, &mut unread, out, first);
                            first = false;
                            let name = c.name.clone();
                            self.expand_def(&file, &name, None, call, depth + 1, out);
                            continue;
                        }
                    }
                    if let Declaration::Association(a) = &mut e.decl {
                        resolve_splats(a, &param, call);
                    }
                    decls += 1;
                    chunk.push(e);
                }
                MacroStep::Delegate {
                    receiver,
                    method,
                    class_arg,
                    ..
                } => {
                    flush(&mut chunk, &mut unread, out, first);
                    first = false;
                    delegates += 1;
                    match self.resolve(&m.owner, receiver) {
                        Some((_, target_file, _)) if depth < MACRO_DEPTH => {
                            let (method, class_arg) = (method.clone(), *class_arg);
                            self.expand_def(
                                &target_file,
                                &method,
                                Some(class_arg),
                                None,
                                depth + 1,
                                out,
                            );
                        }
                        Some(_) => {}
                        None => self
                            .macro_log
                            .push(format!("{def_name}: {receiver} is not in the roots")),
                    }
                }
                MacroStep::Unread(u) => {
                    if hides_registration(u.reason) {
                        hides += 1;
                    }
                    unread.push(u.clone());
                }
            }
        }
        // Forced: after a hand-over or an inner call `first` is false, and the
        // statements read after it (`Definer.call(self); if opts[:x] ... end`)
        // would otherwise never reach a run's `unharvested`.
        flush(&mut chunk, &mut unread, out, true);
        self.macro_log.push(format!(
            "{}#{} ({file}:{}): {decls} declarations, {delegates} hand-overs, {calls} inner calls, {} unread ({hides} may hide a registration)",
            m.owner,
            m.name,
            m.line,
            m.steps
                .iter()
                .filter(|s| matches!(s, MacroStep::Unread(_)))
                .count()
        ));
    }
}

// ─────────────────────────────────────────────────────────────────────────
// Effective registration order
// ─────────────────────────────────────────────────────────────────────────
//
// Four orders are kept apart here:
//   (a) source order of declarations inside one class or module body;
//   (b) concern inclusion order;
//   (c) superclass expansion;
//   (d) the order Rails registers callbacks in, which is what a chain runs in.
// `Harvest::effective` rebuilds (d) from (a)-(c):
//   - a superclass is fully expanded before the class's own body
//     (a class body runs after `class A < B` has loaded B);
//   - `include M` runs M's `included` block at the include statement, in
//     statement order (`ActiveSupport::Concern#append_features`,
//     activesupport-8.1.4.1/lib/active_support/concern.rb:129-140);
//   - first the concern's own dependencies, i.e. the modules it includes in its
//     body (`concern.rb:131` records them, `:135` includes them into the real
//     base, before `:138` runs the included block);
//   - a module already in the ancestors is not re-run (`concern.rb:134`
//     `return false if base < self`), including one a superclass or an earlier
//     concern already brought in;
//   - `prepend` runs the prepended block only (`concern.rb:142-152`), never the
//     included block, so it does not touch callback registration order;
//   - a generated association callback is registered at its association
//     declaration's position (`autosave_association.rb`, called from the macro);
//   - re-registering a symbol filter on the same chain and kind replaces the
//     earlier one and moves it to the end (ActiveSupport::Callbacks,
//     activesupport-8.1.4.1/lib/active_support/callbacks.rb:645-663,
//     `append_one` -> `remove_duplicates` -> `@chain.push`).
// A chain then runs in registration order for before, around and (because
// ActiveModel registers `after_*` with `prepend: true`,
// activemodel-8.1.4.1/lib/active_model/callbacks.rb:146, and the sequence
// compiles the chain in reverse, activesupport callbacks.rb:619-621 with
// `after` pushing at :535-539) after callbacks too.

pub struct EffState {
    pub included: BTreeSet<String>,
    pub out: Vec<Declared>,
    /// The class whose body is being walked; a module's macros run in it.
    pub host: String,
}

impl EffState {
    pub fn push(&mut self, d: Declared) {
        // A generated `validate_associated_records_for_X` is registered only
        // when the method is not yet defined
        // (activerecord-8.1.4.1/lib/active_record/autosave_association.rb:220,
        // `reflection.validate? && !method_defined?(validation_method)`). A
        // re-declared association therefore keeps the first registration in
        // place. Its save callbacks have no such guard (`:197-198`, `:210-211`,
        // `:214`) and move to the end like any re-registered filter.
        if let (Some(_), Filter::Method(name)) = (&d.generated, &d.filter) {
            let already = name.starts_with("validate_associated_records_for_")
                && self.out.iter().any(|e| {
                    e.chain == d.chain
                        && e.kind == d.kind
                        && matches!(&e.filter, Filter::Method(n) if n == name)
                });
            if already {
                return;
            }
        }
        if let Filter::Method(name) = &d.filter {
            self.out.retain(|e| {
                !(e.chain == d.chain
                    && e.kind == d.kind
                    && matches!(&e.filter, Filter::Method(n) if n == name))
            });
        }
        self.out.push(d);
    }
}

impl Harvest {
    /// The model's callbacks in Rails registration order. `patches` are the
    /// engine includes (`oracle/intake.json`), already in `to_prepare` order;
    /// they run after the class body, so their declarations come last. A
    /// `prepend` runs only the prepended block and registers nothing.
    pub fn effective(&mut self, model: &str, patches: &PatchIntake) -> Vec<Declared> {
        let mut st = EffState {
            included: BTreeSet::new(),
            out: Vec::new(),
            host: model.to_string(),
        };
        let mut guard = BTreeSet::new();
        self.eff_class(model, &mut st, &mut guard);
        st.host = model.to_string();
        for p in patches.for_model(model).filter(|p| p.how == How::Include) {
            if let Some((_, ore)) = self.find(&p.patch_name) {
                self.eff_resolved(&p.patch_name, &ore, &mut st);
            }
        }
        st.out
    }

    pub fn eff_class(&mut self, name: &str, st: &mut EffState, guard: &mut BTreeSet<String>) {
        if !guard.insert(name.to_string()) {
            return;
        }
        let Some((_, ore)) = self.find(name) else {
            return;
        };
        let outer = std::mem::replace(&mut st.host, name.to_string());
        if let Some(sup) = ore.superclass.as_deref() {
            if let Some((resolved, ..)) = self.resolve(name, sup) {
                self.eff_class(&resolved, st, guard);
            }
        }
        st.host = name.to_string();
        self.eff_body(name, &ore, false, st);
        st.host = outer;
    }

    /// Walk one body in source order. For a module (`included_only`), only
    /// the `included do` events run on the includer.
    pub fn eff_body(&mut self, name: &str, ore: &ClassOre, included_only: bool, st: &mut EffState) {
        let host = st.host.clone();
        let generated = generated_in(Some(&host), name, ore);
        for e in &ore.declarations {
            let runs = !included_only || matches!(e.origin, DeclOrigin::Included { .. });
            if !runs {
                continue;
            }
            if let Declaration::Concern(c) = &e.decl {
                if matches!(c.kind, ConcernKind::Include) && !c.module.is_empty() {
                    self.eff_include(name, &c.module, st);
                }
                continue;
            }
            for d in declared_of(name, std::slice::from_ref(e)) {
                st.push(d);
            }
            for (seq, g) in &generated.callbacks {
                if *seq == e.seq {
                    st.push(g.clone());
                }
            }
            // A class-level macro registers where it is called, after
            // whatever the call itself declared.
            for run in self.macro_runs_of_decl(e, &ore.file) {
                self.eff_body(&run.owner, &run.ore, false, st);
            }
        }
    }

    pub fn eff_include(&mut self, from: &str, module: &str, st: &mut EffState) {
        let Some((resolved, _, ore)) = self.resolve(from, module) else {
            return;
        };
        self.eff_resolved(&resolved, &ore, st);
    }

    /// `include` of an already resolved module: not again if it is an
    /// ancestor, its dependencies first, then its `included` block.
    pub fn eff_resolved(&mut self, resolved: &str, ore: &ClassOre, st: &mut EffState) {
        let resolved = resolved.to_string();
        if !st.included.insert(resolved.clone()) {
            return;
        }
        // Dependencies: modules included in the module body, before its block.
        let mut deps: Vec<String> = Vec::new();
        for e in &ore.declarations {
            if let (Declaration::Concern(c), DeclOrigin::Body) = (&e.decl, &e.origin) {
                if matches!(c.kind, ConcernKind::Include) && !c.module.is_empty() {
                    deps.push(c.module.clone());
                }
            }
        }
        for i in &ore.includes {
            if matches!(i.kind, ConcernKind::Include)
                && matches!(i.origin, DeclOrigin::Body)
                && !deps.contains(&i.module)
            {
                deps.push(i.module.clone());
            }
        }
        for d in deps {
            self.eff_include(&resolved, &d, st);
        }
        self.eff_body(&resolved, ore, true, st);
    }
}

