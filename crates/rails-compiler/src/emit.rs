//! Deterministic Rust emission.
//!
//! Output depends only on the harvest: collections are ordered maps or
//! ruff/Rails declaration order, nothing carries a timestamp, and every
//! callback entry carries the source location and rule that produced it.
//! Regenerating from the same source yields byte-identical files.

use std::fmt::Write as _;
use std::path::Path;

use crate::{Binding, Compilation, CompiledModel};
use crate::lower::const_ident;

const HEADER: &str = "// @generated by rails-compiler — do not edit.\n// Regenerate: ZAMMAD_SRC=<zammad checkout> cargo run -p rails-compiler -- zammad.toml\n";

fn col_type(ty: &str, store: bool) -> &'static str {
    if store {
        return "Json";
    }
    match ty {
        "string" => "String",
        "text" | "binary" => "Text",
        "integer" | "bigint" => "Integer",
        "boolean" => "Boolean",
        "datetime" | "timestamp" | "date" | "time" => "DateTime",
        "decimal" | "float" => "Decimal",
        "json" | "jsonb" => "Json",
        _ => "Text",
    }
}

fn default_expr(d: &crate::schema::Default) -> String {
    match d {
        crate::schema::Default::None | crate::schema::Default::Expr(_) => "rp::Default::None".into(),
        crate::schema::Default::Int(i) => format!("rp::Default::Int({i})"),
        crate::schema::Default::Str(s) => format!("rp::Default::Str({s:?})"),
        crate::schema::Default::Bool(b) => format!("rp::Default::Bool({b})"),
    }
}

fn on_expr(on: &Option<Vec<String>>) -> String {
    match on {
        None => "On::ANY".into(),
        Some(v) => format!(
            "On {{ create: {}, update: {}, destroy: {} }}",
            v.iter().any(|a| a == "create"),
            v.iter().any(|a| a == "update"),
            v.iter().any(|a| a == "destroy")
        ),
    }
}

fn phase_expr(p: &str) -> String {
    p.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next().map_or_else(String::new, |f| f.to_uppercase().chain(c).collect())
        })
        .collect()
}

fn model(m: &CompiledModel, c: &Compilation, stores: &[String]) -> String {
    let mut s = String::from(HEADER);
    let _ = writeln!(s, "//! `{}` — table `{}` ({}), from {}", m.name, m.table, m.table_provenance, m.source_files.join(", "));
    let _ = writeln!(s, "//!");
    let _ = writeln!(s, "//! Ancestors (Ruby MRO): {}", m.ancestors.join(" → "));
    let _ = writeln!(
        s,
        "//! OGAR lift: `{}` < {:?}, {} associations, {} callbacks, {} validations, {} mixins.",
        m.ogar.name, m.ogar.parent, m.ogar.associations, m.ogar.callbacks, m.ogar.validations, m.ogar.mixins
    );
    s.push_str("#![allow(clippy::all, clippy::pedantic, dead_code, unused_imports, unreachable_code, unused_braces, unused_parens)]\n\n");
    s.push_str("use std::sync::LazyLock;\n\nuse rails_polyfill as rp;\nuse rp::{Callback, Cond, On, Phase, Target};\n\n");

    let table = &c.schema.tables[&m.table];
    s.push_str("/// Column ordinals.\npub mod col {\n");
    for (i, col) in table.columns.iter().enumerate() {
        let _ = writeln!(s, "    pub const {}: usize = {i};", const_ident(&col.name));
    }
    s.push_str("}\n\n");
    let _ = writeln!(s, "pub static TABLE: rp::TableSpec = rp::TableSpec {{\n    name: {:?},\n    columns: &[", m.table);
    for col in &table.columns {
        let _ = writeln!(
            s,
            "        rp::Column {{ name: {:?}, ty: rp::ColumnType::{}, null: {}, default: {}, limit: {:?} }}, // {}",
            col.name,
            col_type(&col.ty, stores.contains(&col.name)),
            col.null,
            default_expr(&col.default),
            col.limit,
            col.provenance
        );
    }
    s.push_str("    ],\n};\n\n");
    let _ = writeln!(
        s,
        "pub static MODEL: rp::ModelSpec = rp::ModelSpec {{ name: {:?}, table: &TABLE, callbacks: &CALLBACKS }};\n",
        m.name
    );

    let _ = writeln!(s, "/// Navigable associations.\npub static ASSOCIATIONS: &[rp::lifecycle::AssocSpec] = &[");
    for (name, kind, fk, target, order, prov) in &m.navigable {
        let Some(t) = c.models.iter().find(|x| &x.name == target) else { continue };
        let tpath = if t.name == m.name { String::new() } else { format!("crate::{}::", t.module) };
        let (kind, fk_path) = match kind.as_str() {
            "belongs_to" => ("BelongsTo", format!("col::{}", const_ident(fk))),
            "has_one" => ("HasOne", format!("{tpath}col::{}", const_ident(fk))),
            _ => ("HasMany", format!("{tpath}col::{}", const_ident(fk))),
        };
        let order: Vec<String> = order.iter().map(|o| format!("{tpath}col::{}", const_ident(o))).collect();
        let _ = writeln!(
            s,
            "    rp::lifecycle::AssocSpec {{ name: {name:?}, kind: rp::lifecycle::AssocKind::{kind}, fk: {fk_path}, target: &{tpath}MODEL, order: &[{}], provenance: {prov:?} }},",
            order.join(", ")
        );
    }
    s.push_str("];\n\n");

    // Condition and callback wrappers.
    let mut wrappers = String::new();
    let mut wrapped = std::collections::BTreeSet::new();
    let mut wrap = |ident: &str, wrappers: &mut String| -> String {
        let w = format!("cb_{}", ident.trim_start_matches("m_"));
        if wrapped.insert(w.clone()) {
            let _ = writeln!(
                wrappers,
                "fn {w}(ctx: &mut rp::Ctx, rec: &mut rp::Record) -> Result<rp::Value, rp::Halt> {{ {ident}(ctx, rec, &[]) }}"
            );
        }
        w
    };

    let _ = writeln!(s, "/// The linearized callback chains, in execution order.\npub static CALLBACKS: [Callback; {}] = [", m.chain.len());
    for e in &m.chain {
        let target = match &e.binding {
            Binding::Lowered(f) => format!("Target::Lowered({})", wrap(f, &mut wrappers)),
            Binding::Host => "Target::Host".into(),
            Binding::Framework => "Target::Framework".into(),
            Binding::Residual(r) => format!("Target::Residual({r:?})"),
            Binding::Validator(v) => {
                let parts: Vec<&str> = v.split(':').collect();
                match parts.as_slice() {
                    ["presence", a] => format!(
                        "Target::Validator(rp::validations::Validator::Presence {{ column: col::{}, attr: {a:?} }})",
                        const_ident(a)
                    ),
                    ["length", a, min, max] => {
                        let opt = |x: &str| if x == "-" { "None".to_string() } else { format!("Some({x})") };
                        format!(
                            "Target::Validator(rp::validations::Validator::Length {{ column: col::{}, attr: {a:?}, min: {}, max: {} }})",
                            const_ident(a),
                            opt(min),
                            opt(max)
                        )
                    }
                    ["belongs_to_required", assoc, fk, target, cond] => {
                        let t = c.models.iter().find(|x| x.name == *target);
                        let tpath = t.map_or(String::new(), |t| if t.name == m.name { String::new() } else { format!("crate::{}::", t.module) });
                        format!(
                            "Target::Validator(rp::validations::Validator::BelongsToRequired {{ assoc: {assoc:?}, fk: col::{}, target: &{tpath}MODEL, only_if_fk_missing_or_changed: {cond} }})",
                            const_ident(fk)
                        )
                    }
                    _ => "Target::Validator(rp::validations::Validator::Host)".into(),
                }
            }
        };
        let conds: Vec<String> = e
            .conds
            .iter()
            .map(|(kind, code)| {
                let ctor = if kind == "if" { "If" } else { "Unless" };
                if let Some(b) = code.strip_prefix("builtin:") {
                    let f = format!("builtin_{}", crate::lower::fn_ident("", b));
                    format!("Cond::{ctor}({f})")
                } else if let Some(f) = code.strip_prefix("fn:") {
                    if f.starts_with("lam_") {
                        format!("Cond::{ctor}({f})")
                    } else {
                        format!("Cond::{ctor}({})", wrap(f, &mut wrappers))
                    }
                } else {
                    format!("Cond::Residual({:?})", code.trim_start_matches("residual:"))
                }
            })
            .collect();
        let _ = writeln!(
            s,
            "    Callback {{ phase: Phase::{}, name: {:?}, on: {}, conds: &[{}], target: {target}, provenance: {:?} }},",
            phase_expr(&e.phase),
            e.name,
            on_expr(&e.on),
            conds.join(", "),
            format!("{} [{}]", e.provenance, e.rule)
        );
    }
    s.push_str("];\n\n");
    s.push_str("fn builtin_new_record_q(_: &mut rp::Ctx, rec: &mut rp::Record) -> Result<rp::Value, rp::Halt> { Ok(rp::Value::Bool(rec.new_record())) }\n");
    s.push_str("fn builtin_persisted_q(_: &mut rp::Ctx, rec: &mut rp::Record) -> Result<rp::Value, rp::Halt> { Ok(rp::Value::Bool(rec.persisted())) }\n\n");
    s.push_str(&wrappers);
    s.push('\n');
    for (i, re) in m.code.regexes.iter().enumerate() {
        let _ = writeln!(
            s,
            "static RE_{i}: LazyLock<regex::Regex> = LazyLock::new(|| regex::Regex::new({re:?}).expect(\"validated by the compiler\"));"
        );
    }
    s.push('\n');
    for code in m.code.fns.values() {
        s.push_str(code);
        s.push('\n');
    }
    s
}

pub fn write(c: &Compilation, stores: &std::collections::BTreeMap<String, Vec<String>>, out: &Path) -> std::io::Result<Vec<String>> {
    let src = out.join("src");
    std::fs::create_dir_all(&src)?;
    let mut written = Vec::new();
    for m in &c.models {
        let path = src.join(format!("{}.rs", m.module));
        std::fs::write(&path, model(m, c, stores.get(&m.name).map_or(&[][..], Vec::as_slice)))?;
        written.push(path.display().to_string());
    }
    let mut rel = String::from(HEADER);
    rel.push_str("//! Relation semantics derived by the `R-REL-*` rules: `(subject, predicate, object, rule)`.\n\n");
    let _ = writeln!(rel, "pub static RELATIONS: &[(&str, &str, &str, &str)] = &[");
    for r in &c.relations {
        let _ = writeln!(rel, "    ({:?}, {:?}, {:?}, {:?}),", r.subject, r.predicate, r.object, r.rule);
    }
    rel.push_str("];\n");
    std::fs::write(src.join("relations.rs"), rel)?;
    let mut lib = String::from(HEADER);
    let _ = writeln!(lib, "//! The `{}` slice, compiled. Every module is generated.\n", c.app);
    for m in &c.models {
        let _ = writeln!(lib, "pub mod {};", m.module);
    }
    lib.push_str("pub mod relations;\n\n/// Every compiled model.\npub static MODELS: &[&rails_polyfill::ModelSpec] = &[\n");
    for m in &c.models {
        let _ = writeln!(lib, "    &{}::MODEL,", m.module);
    }
    lib.push_str("];\n");
    std::fs::write(src.join("lib.rs"), lib)?;
    Ok(written)
}
